export function Icon({ name, className }: { name: string; className?: string }) {
  const C = ICONS[name] ?? CircleHelp;
  return <C className={className ?? "size-4"} />;
}

/** Icono dentro de un círculo del color de la categoría o cuenta. */
export function IconBadge({ icon, color, size = "md" }: { icon: string; color: string; size?: "sm" | "md" }) {
  const box = size === "sm" ? "size-7" : "size-9";
  const inner = size === "sm" ? "size-3.5" : "size-4.5";
  return (
    <span
      className={`inline-flex ${box} shrink-0 items-center justify-center rounded-full`}
      style={{ backgroundColor: `${color}22`, color }}
    >
      <Icon name={icon} className={inner} />
    </span>
  );
}
